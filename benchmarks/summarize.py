#!/usr/bin/env python3
"""Generate numeric tables from a universal.py report, without source or gold access."""
import argparse
import json
from pathlib import Path
from statistics import mean, median


def pct(value):
    return '-' if value is None else f'{100 * value:.1f}%'


def table(headers, rows):
    return '\n'.join(['| ' + ' | '.join(headers) + ' |',
                      '| ' + ' | '.join(['---'] * len(headers)) + ' |'] +
                     ['| ' + ' | '.join(str(x) for x in row) + ' |' for row in rows])


def summarize(report):
    runs = report['runs']

    def cases(variant, scope='native', split='all', negative=False):
        return [c for r in runs if r['variant'] == variant and r['scope'] == scope
                and (split == 'all' or r['split'] == split) for c in r['cases']
                if (c['kind'] == 'negative') == negative]

    before = {c['id']: c for c in cases('before')}
    after = {c['id']: c for c in cases('after')}
    lines = ['# Numeric evaluation tables', '',
             'Generated by `python benchmarks/summarize.py --report benchmarks/results/comparison.json`.',
             'See [interpretation and limitations](../RESULTS.md) and [protocol](../PROTOCOL.md).', '',
             'Tokenizer: **' + report['tiktoken'] + ' / ' + report['tokenizer'] + '**. '
             'All token counts below are measured response tokens, not the CLI byte proxy.', '',
             '## Ranking (positive cases)', '']
    rows = []
    for scope in ('native', 'intersection'):
        for split in ('dev', 'heldout', 'all'):
            for variant in ('before', 'after'):
                cs = cases(variant, scope, split)
                rows.append([scope, split, variant, len(cs)] +
                            [pct(mean(c[k] for c in cs)) for k in ('hit1', 'mrr5', 'ndcg5', 'artifact_recall5')])
    lines += [table(['Scope', 'Split', 'Variant', 'N', 'Hit@1', 'MRR@5', 'nDCG@5', 'Artifact recall@5'], rows), '',
              '## Equal total response budgets (sequential policy)', '']
    rows = []
    for scope in ('native', 'intersection'):
        for split in ('dev', 'heldout', 'all'):
            for form in ('native', 'canonical'):
                for budget in ('1000', '2000', '4000', '8000'):
                    values = [mean(c['curves'][form][budget]['evidence_coverage'] for c in cases(v, scope, split))
                              for v in ('before', 'after')]
                    rows.append([scope, split, form, budget] + [pct(v) for v in values])
    lines += [table(['Scope', 'Split', 'Format', 'Token cap', 'Before coverage', 'After coverage'], rows), '',
              '## Discovery', '']
    rows = []
    for b in [r for r in runs if r['variant'] == 'before' and r['scope'] == 'native']:
        a = next(r for r in runs if r['repo'] == b['repo'] and r['variant'] == 'after' and r['scope'] == 'native')
        rows.append([b['repo'], b['tracked_files'], b['indexed_files'], a['indexed_files'], b['discovery_required'],
                     ', '.join(b['discovery_omissions']) or 'none', ', '.join(a['discovery_omissions']) or 'none'])
    lines += [table(['Repo', 'Tracked', 'Before indexed', 'After indexed', 'Required audit paths', 'Before omissions', 'After omissions'], rows), '',
              '## Cost at comparable evidence coverage', '',
              'Medians over paired cases where **both** variants reached the target. '
              'Reached counts disclose cases excluded from that paired comparison.', '']
    rows = []
    for form in ('native', 'canonical'):
        for target in ('0.5', '0.8', '1.0'):
            pairs = [(b['cost_at_coverage'][form][target], after[k]['cost_at_coverage'][form][target]) for k, b in before.items()]
            paired = [(b, a) for b, a in pairs if b is not None and a is not None]
            rows.append([form, pct(float(target)), sum(b is not None for b, _ in pairs),
                         sum(a is not None for _, a in pairs), len(paired),
                         median(b for b, _ in paired) if paired else '-', median(a for _, a in paired) if paired else '-'])
    lines += [table(['Format', 'Coverage target', 'Before reached /24', 'After reached /24', 'Paired N', 'Before tokens', 'After tokens'], rows), '',
              '## Response overhead', '',
              'The fixed policy permits different numbers of actual pages and follow-ups. '
              'These mean full-trace sizes are **not** an equal-coverage cost comparison.', '']
    rows = []
    for variant in ('before', 'after'):
        cs = cases(variant)
        rows.append([variant, f'{mean(len(c["trace"]) for c in cs):.2f}'] +
                    [round(mean(sum(s[form + '_tokens'] for s in c['trace']) for c in cs)) for form in ('native', 'canonical')] +
                    [round(mean(c['trace'][0][form + '_tokens'] for c in cs)) for form in ('native', 'canonical')])
    lines += [table(['Variant', 'Mean responses', 'Native full trace', 'Canonical full trace', 'Native first query', 'Canonical first query'], rows), '',
              '## Collection (different workflow)', '',
              'Each row is a separate single `collect` call. Byte-proxy budgets below are '
              '**not** equal measured-token caps; all metadata and excerpts are included in token counts.', '']
    rows = []
    for split in ('dev', 'heldout', 'all'):
        for budget in (400, 900, 1800, 3600):
            values = [v for c in cases('after', split=split) for v in c['collect'] if v['byte_budget'] == budget]
            rows.append([split, budget, round(mean(v['native_tokens'] for v in values)), max(v['native_tokens'] for v in values),
                         pct(mean(v['evidence_coverage'] for v in values)), pct(mean(v['artifact_coverage'] for v in values))])
    lines += [table(['Split', 'Byte-proxy budget', 'Mean measured tokens', 'Max measured tokens', 'Evidence coverage', 'Complete artifact coverage'], rows), '',
              '## Every positive case (native scope)', '']
    rows = []
    for key, b in before.items():
        a = after[key]
        rows.append([key, str(b['first_relevant_rank'] or '-') + ' / ' + str(a['first_relevant_rank'] or '-'),
                     pct(b['artifact_recall5']) + ' / ' + pct(a['artifact_recall5']),
                     pct(b['curves']['native']['4000']['evidence_coverage']) + ' / ' + pct(a['curves']['native']['4000']['evidence_coverage']),
                     pct(b['curves']['native']['8000']['evidence_coverage']) + ' / ' + pct(a['curves']['native']['8000']['evidence_coverage'])])
    lines += [table(['Case', 'First relevant rank B/A', 'Artifact recall@5 B/A', 'Evidence @4k B/A', 'Evidence @8k B/A'], rows), '',
              '## Individual regressions', '',
              'All reductions in rank quality, artifact recall, or evidence coverage at '
              'any measured cap, in either response format. Values are before to after.', '']
    rows = []
    for scope in ('native', 'intersection'):
        bs = {c['id']: c for c in cases('before', scope)}
        for a in cases('after', scope):
            b = bs[a['id']]
            changes = []
            for k in ('hit1', 'mrr5', 'ndcg5', 'artifact_recall5'):
                if a[k] < b[k]:
                    changes.append(f'{k}: {pct(b[k])} to {pct(a[k])}')
            for form in ('native', 'canonical'):
                for cap in ('1000', '2000', '4000', '8000'):
                    bv, av = (c['curves'][form][cap]['evidence_coverage'] for c in (b, a))
                    if av < bv:
                        changes.append(f'{form} @{cap}: {pct(bv)} to {pct(av)}')
            if changes:
                rows.append([scope, a['id'], '; '.join(changes)])
    lines += [table(['Scope', 'Case', 'Regressions'], rows), '', '## Negative cases', '']
    rows = []
    bneg = {c['id']: c for c in cases('before', negative=True)}
    for c in cases('after', negative=True):
        rows.append([c['id'], bneg[c['id']]['negative_has_hits'], c['negative_has_hits'], c['assessment'],
                     ', '.join(sorted({v['stop_reason'] for v in c['collect']}))])
    lines += [table(['Case', 'Before has hits', 'After has hits', 'After assessment', 'Collect stopping reasons'], rows), '',
              'Related lexical hits are not automatically false answers. The tool never generates an answer; '
              'these cases test absence of relevant evidence and whether uncertainty is exposed.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--report', type=Path, required=True)
    p.add_argument('--output', type=Path, default=Path('benchmarks/results/TABLES.md'))
    args = p.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(summarize(json.loads(args.report.read_text(encoding='utf-8'))).encode('utf-8'))
